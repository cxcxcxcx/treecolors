#!/usr/bin/env python3
"""Write or check the city table in README.md.

The table is generated from `web/species_stats.json` (the same file the map
reads) and `py/tree_pipeline/cities.py`, so it lists every city on the map and
cannot drift from the data. CI runs `--check`, so a stale README fails the
build.

    python3 scripts/readme_cities.py            # rewrite the block
    python3 scripts/readme_cities.py --check    # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "py"))

from tree_pipeline.cities import CITIES  # noqa: E402

README = ROOT / "README.md"
STATS = ROOT / "web" / "species_stats.json"
START = "<!-- cities:start -->"
END = "<!-- cities:end -->"


def city_table() -> str:
    cities = json.loads(STATS.read_text(encoding="utf-8"))["cities"]
    registry = {city.slug for city in CITIES}
    rows = []
    for city in cities:
        turn = sum(s["count"] for s in city["species"] if s.get("color_range") in ("red", "orange"))
        rows.append((city["name"], city["total"], round(100 * turn / city["total"]), city["slug"]))
    rows.sort(key=lambda r: -r[1])
    total = sum(r[1] for r in rows)
    turn = sum(
        s["count"]
        for c in cities
        for s in c["species"]
        if s.get("color_range") in ("red", "orange")
    )
    lines = [
        START,
        "<!-- Generated by scripts/readme_cities.py from web/species_stats.json. Do not edit by hand. -->",
        "",
        f"**{len(rows)} cities · {total:,} trees · {round(100 * turn / total)}% turn in autumn.** "
        "Counts are from the last `web-assets` run.",
        "",
        "| City | Trees | Turn | Added via | Slug |",
        "|---|---:|---:|---|---|",
    ]
    for name, trees, pct, slug in rows:
        via = "registry" if slug in registry else "legacy import"
        lines.append(f"| {name} | {trees:,} | {pct}% | {via} | `{slug}` |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if README.md is stale")
    args = parser.parse_args()

    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md has no {START} … {END} block")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    current = START + city_table().split(START, 1)[1].rsplit(END, 1)[0] + END
    expected = head + current + tail

    if args.check:
        if text != expected:
            print("README.md city table is stale; run: python3 scripts/readme_cities.py", file=sys.stderr)
            return 1
        print("README.md city table is current")
        return 0

    if text != expected:
        README.write_text(expected, encoding="utf-8")
        print("updated the city table in README.md")
    else:
        print("README.md city table already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
