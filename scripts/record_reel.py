#!/usr/bin/env python3
"""Record assets/promo/reel.html to a vertical MP4 (TikTok / Reels / 小红书).

The animation lives in HTML/CSS on a single clock. Instead of screen-recording
in real time, we seek that clock frame by frame (window.render(t)) and take a
screenshot of each frame, so the output is perfectly smooth however slow the
machine is. Frames are piped straight into ffmpeg — nothing large hits disk.

    python3 scripts/record_reel.py              # zh + en
    python3 scripts/record_reel.py --lang zh    # promo/instagram/zh/reel.mp4
    python3 scripts/record_reel.py --data-only  # just refresh reel-data.js for the live preview
    python3 scripts/record_reel.py --lang en --hook planted   # alternative opening → reel-planted.mp4

Numbers are written to promo/instagram/reel-data.js from web/species_stats.json
(same computation as make_promo.py), so the video never drifts from the app.
"""

from __future__ import annotations

import argparse
import base64
import json
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

import websocket

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_promo import stats  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "assets" / "promo" / "reel.html"
DATA_JS = ROOT / "promo" / "instagram" / "reel-data.js"
OUT = {"en": ROOT / "promo" / "instagram" / "reel.mp4",
       "zh": ROOT / "promo" / "instagram" / "zh" / "reel.mp4"}
WORK = ROOT / "data" / "work" / "reel"
CHROME = shutil.which("google-chrome-stable") or shutil.which("google-chrome")
WIDTH, HEIGHT = 1080, 1920


def write_data() -> None:
    info = stats()
    data = {
        "bay_trees": info["bay_trees"],
        "bay_fall": info["bay_fall"],
        "bay_cities": info["bay_cities"],
        "plates": info["plates"],
        "city": {slug: {"total": c["total"], "fall": c["fall"]} for slug, c in info["city"].items()},
    }
    DATA_JS.parent.mkdir(parents=True, exist_ok=True)
    DATA_JS.write_text("// generated by scripts/record_reel.py — do not edit\n"
                       f"window.REEL_DATA = {json.dumps(data)};\n")


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def start_chrome(port: int, profile: str) -> subprocess.Popen:
    if not CHROME:
        raise SystemExit("Chrome not found")
    proc = subprocess.Popen(
        [CHROME, "--headless=new", f"--remote-debugging-port={port}",
         f"--remote-allow-origins=http://127.0.0.1:{port}",
         f"--user-data-dir={profile}", "--no-first-run", "--disable-gpu",
         "--disable-dev-shm-usage", "--hide-scrollbars", "--allow-file-access-from-files",
         f"--window-size={WIDTH},{HEIGHT}", "about:blank"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(80):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{port}/json/version", timeout=1).read()
            return proc
        except Exception:
            time.sleep(0.5)
    proc.kill()
    raise SystemExit("chrome did not start")


class Tab:
    def __init__(self, port: int):
        request = urllib.request.Request(f"http://127.0.0.1:{port}/json/new?about:blank", method="PUT")
        tab = json.load(urllib.request.urlopen(request))
        self.ws = websocket.create_connection(tab["webSocketDebuggerUrl"], timeout=120,
                                              origin=f"http://127.0.0.1:{port}")
        self.counter = 0

    def send(self, method: str, params: dict | None = None) -> dict:
        self.counter += 1
        self.ws.send(json.dumps({"id": self.counter, "method": method, "params": params or {}}))
        while True:
            message = json.loads(self.ws.recv())
            if message.get("id") == self.counter:
                if "error" in message:
                    raise RuntimeError(f"{method}: {message['error']}")
                return message.get("result", {})

    def eval(self, expression: str):
        result = self.send("Runtime.evaluate", {"expression": expression, "awaitPromise": True,
                                                "returnByValue": True})
        if "exceptionDetails" in result:
            raise RuntimeError(result["exceptionDetails"])
        return result["result"].get("value")


def out_path(lang: str, hook: str | None) -> Path:
    return OUT[lang].with_stem(f"reel-{hook}") if hook else OUT[lang]


def load(tab: Tab, lang: str, hook: str | None = None) -> dict:
    url = f"{PAGE.as_uri()}?lang={lang}&record=1&v={time.time_ns()}" + (f"&hook={hook}" if hook else "")
    tab.send("Page.navigate", {"url": url})
    for _ in range(100):  # wait for *this* navigation, not the previous language's page
        time.sleep(0.2)
        if tab.eval(f"location.href === {json.dumps(url)} && document.readyState === 'complete'"):
            break
    ready = tab.eval("window.reelReady")
    if ready["missing"] or not ready["hasData"]:
        raise SystemExit(f"page not ready: {ready}")
    return ready


def frame(tab: Tab, t: float) -> bytes:
    # two rAFs: the seek has been styled and painted before we capture
    tab.eval(f"render({t}); new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))")
    return base64.b64decode(tab.send("Page.captureScreenshot", {"format": "png"})["data"])


def peek(tab: Tab, lang: str, times: list[float], hook: str | None) -> None:
    load(tab, lang, hook)
    for t in times:
        path = WORK / f"{lang}{'-' + hook if hook else ''}-{t:05.2f}.png"
        path.write_bytes(frame(tab, t))
        print(path.relative_to(ROOT))


def record(tab: Tab, lang: str, fps: int, out: Path, hook: str | None) -> None:
    ready = load(tab, lang, hook)
    frames = int(round(ready["seconds"] * fps))
    out.parent.mkdir(parents=True, exist_ok=True)
    ffmpeg = subprocess.Popen([
        "ffmpeg", "-y", "-loglevel", "error", "-f", "image2pipe", "-framerate", str(fps),
        "-c:v", "png", "-i", "-",
        "-c:v", "libx264", "-preset", "slow", "-crf", "20", "-pix_fmt", "yuv420p",
        "-movflags", "+faststart", str(out),
    ], stdin=subprocess.PIPE)
    started = time.time()
    for index in range(frames):
        ffmpeg.stdin.write(frame(tab, index / fps))
        if index % fps == 0:
            print(f"\r  {lang}: {index / fps:4.1f}/{ready['seconds']} s", end="", flush=True)
    ffmpeg.stdin.close()
    if ffmpeg.wait():
        raise SystemExit("ffmpeg failed")
    print(f"\r  {lang}: {frames} frames → {out.relative_to(ROOT)} "
          f"({out.stat().st_size / 1024 / 1024:.1f} MB, {time.time() - started:.0f} s)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lang", choices=["zh", "en", "both"], default="both")
    parser.add_argument("--fps", type=int, default=30)
    parser.add_argument("--data-only", action="store_true")
    parser.add_argument("--hook", help="alternative opening from HOOKS in reel.html, e.g. planted")
    parser.add_argument("--peek", help="comma-separated seconds: save those frames as PNGs in data/work/reel/ instead")
    args = parser.parse_args()

    write_data()
    if args.data_only:
        print(f"wrote {DATA_JS.relative_to(ROOT)}")
        return 0

    WORK.mkdir(parents=True, exist_ok=True)
    port = free_port()
    profile = tempfile.mkdtemp(prefix="chrome-", dir=WORK)
    proc = start_chrome(port, profile)
    try:
        tab = Tab(port)
        tab.send("Page.enable")
        tab.send("Emulation.setDeviceMetricsOverride",
                 {"width": WIDTH, "height": HEIGHT, "deviceScaleFactor": 1, "mobile": False})
        for lang in (["zh", "en"] if args.lang == "both" else [args.lang]):
            if args.peek:
                peek(tab, lang, [float(t) for t in args.peek.split(",")], args.hook)
            else:
                record(tab, lang, args.fps, out_path(lang, args.hook), args.hook)
        tab.ws.close()
    finally:
        proc.terminate()
        shutil.rmtree(profile, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
